# Intentionally empty for LiMBS1.0 until specific construction defaults
# are validated for defined conditions. This prevents a reference APL from
# accidentally becoming a universal builder default.
BUILDER_DEFAULT_APL_NM2: Dict[str, float] = {}


def normalize_lipid_name(lipid: str) -> str:
    """Normalize a lipid name for registry lookup."""
    return str(lipid).strip().upper()


def has_apl_reference(lipid: str) -> bool:
    """Return True when a pure-system Martini 3 APL reference is available."""
    return normalize_lipid_name(lipid) in APL_REFERENCES


def get_apl_reference(lipid: str) -> Optional[Dict[str, Any]]:
    """
    Return a copy of the Martini 3 pure-bilayer APL reference for `lipid`.

    Returns None when the lipid is not present.
    """
    record = APL_REFERENCES.get(normalize_lipid_name(lipid))
    return None if record is None else dict(record)


def get_apl_nm2(lipid: str) -> Optional[float]:
    """Return the reference APL in nm^2/lipid, or None if unavailable."""
    record = get_apl_reference(lipid)
    return None if record is None else record["apl_nm2"]


def get_builder_default_apl_nm2(lipid: str) -> Optional[float]:
    """
    Return an explicitly curated construction default, if one exists.

    This is intentionally separate from `get_apl_nm2()`. A pure-bilayer
    reference value must not automatically become a builder default.
    """
    return BUILDER_DEFAULT_APL_NM2.get(normalize_lipid_name(lipid))


def available_apl_lipids() -> List[str]:
    """Return all lipid names with a Martini 3 pure-system APL reference."""
    return sorted(APL_REFERENCES)


def ui_apl_record(lipid: str) -> Optional[Dict[str, Any]]:
    """
    Return a small record suitable for displaying in the LiMBS web UI.

    The returned label intentionally says "reference" rather than "default".
    """
    record = get_apl_reference(lipid)
    if record is None:
        return None

    return {
        "lipid": normalize_lipid_name(lipid),
        "value_nm2": record["apl_nm2"],
        "se_nm2": record["apl_se_nm2"],
        "label": "Martini 3 pure-bilayer reference APL",
        "source": f'Pedersen et al., ACS Central Science ({SOURCE["year"]})',
        "doi": SOURCE["doi"],
        "warning": (
            "Reference value only. APL depends on membrane composition, "
            "thermodynamic state, and simulation conditions; users may "
            "override this value."
        ),
    }


def summary() -> Dict[str, Any]:
    """Return basic information about this APL reference module."""
    return {
        "source": dict(SOURCE),
        "number_of_reference_lipids": len(APL_REFERENCES),
        "number_of_builder_defaults": len(BUILDER_DEFAULT_APL_NM2),
        "units": {
            "apl_A2": "A^2/lipid",
            "apl_nm2": "nm^2/lipid",
        },
    }


if __name__ == "__main__":
    info = summary()
    print(
        f'Loaded {info["number_of_reference_lipids"]} Martini 3 '
        "pure-bilayer APL reference values."
    )

    for lipid in ("POPC", "DOPC", "POPE", "DPPC"):
        ref = get_apl_reference(lipid)
        if ref:
            print(
                f'{lipid:5s}  {ref["apl_nm2"]:.5f} nm^2/lipid '
                f'(source APL = {ref["apl_A2"]:.3f} A^2/lipid)'
            )
